#!/usr/bin/env python3
"""Generate a minimal data-driven BP/RP Bedrock project (no Script API by default)."""
from __future__ import annotations
import argparse
import json
import re
import uuid
from pathlib import Path


def slugify(value: str) -> str:
    slug = re.sub(r"[^a-z0-9_]+", "_", value.lower()).strip("_")
    return slug or "bedrock_addon"


def write_json(path: Path, data: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description="Create a basic Bedrock BP/RP project")
    ap.add_argument("name", help="Display name of the add-on")
    ap.add_argument("--out", default=".", help="Output folder")
    ap.add_argument("--namespace", help="Custom namespace; defaults to a slug of the project name")
    ap.add_argument("--minimum-bedrock", default="1.21.0", help="Minimum engine version, default 1.21.0")
    args = ap.parse_args()
    parts = args.minimum_bedrock.split(".")
    if len(parts) != 3 or not all(x.isdigit() for x in parts):
        ap.error("--minimum-bedrock must use major.minor.patch, for example 1.21.0")
    minimum = [int(x) for x in parts]
    name = args.name.strip()
    ns = slugify(args.namespace or name)
    out = Path(args.out).expanduser().resolve()
    bp, rp = out / "BP", out / "RP"
    if out.exists() and any(out.iterdir()):
        ap.error(f"Output folder is not empty: {out}; choose a new folder")
    bp_header, rp_header = str(uuid.uuid4()), str(uuid.uuid4())
    bp_module, rp_module = str(uuid.uuid4()), str(uuid.uuid4())
    pack_version = [1, 0, 0]
    common_header = {"name": name, "description": "Behavior Pack generated by Bedrock AI Architect V6", "uuid": bp_header, "version": pack_version, "min_engine_version": minimum}
    bp_manifest = {"format_version": 2, "header": common_header, "modules": [{"type": "data", "uuid": bp_module, "version": pack_version}], "dependencies": [{"uuid": rp_header, "version": pack_version}]}
    rp_manifest = {"format_version": 2, "header": {"name": f"{name} Resources", "description": "Resource Pack generated by Bedrock AI Architect V6", "uuid": rp_header, "version": pack_version, "min_engine_version": minimum}, "modules": [{"type": "resources", "uuid": rp_module, "version": pack_version}]}
    write_json(bp / "manifest.json", bp_manifest)
    write_json(rp / "manifest.json", rp_manifest)
    for folder in ("entities", "items", "blocks", "recipes", "loot_tables", "functions", "scripts"):
        (bp / folder).mkdir(parents=True, exist_ok=True)
    for folder in ("models/entity", "models/blocks", "textures/entity", "textures/items", "textures/blocks", "textures/particle", "particles", "animations", "animation_controllers", "render_controllers", "attachables", "texts"):
        (rp / folder).mkdir(parents=True, exist_ok=True)
    config = {"schemaVersion": 1, "project": {"name": name, "namespace": ns}, "compatibility": {"minimumBedrock": args.minimum_bedrock, "latestStableVerifiedAtBuild": "26.60", "snapshotDate": "2026-10-30", "policy": "1.21+; test every target version; create separate Script API profiles when required"}, "scriptApi": {"enabled": False, "reason": "No se añadió Script API para conservar la compatibilidad data-driven más amplia. Añádela solo tras elegir versión y dependencia."}, "audio": {"included": False, "note": "El usuario añadirá archivos de sonido manualmente."}}
    write_json(out / "bedrock.config.json", config)
    (out / "README.md").write_text(f"# {name}\n\nNamespace: `{ns}`\n\nProyecto BP/RP inicial creado por Bedrock AI Architect V6. No incluye scripts ni activos runtime todavía. Define primero tu idea y versión objetivo, después implementa y valida.\n", encoding="utf-8")
    print(f"Proyecto creado: {out}")
    print("Carpetas: BP/ y RP/; Script API no activada por defecto.")
    print("Ejecuta: python tools/validate_addon.py <ruta-del-proyecto>")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
